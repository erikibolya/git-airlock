//go:build windows

package install

import (
	"encoding/binary"
	"fmt"
	"html"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
	"unicode/utf16"
)

func installWindows(o Options) error {
	local := os.Getenv("LOCALAPPDATA")
	if local == "" {
		return fmt.Errorf("LOCALAPPDATA is not set")
	}
	dir := filepath.Join(local, "git-airlock")
	vbs := filepath.Join(dir, "worker.vbs")
	content := fmt.Sprintf(`' Generated by Git Airlock.
' Runs the worker silently every %s.
Dim sh, rc
Set sh = CreateObject("WScript.Shell")
rc = sh.Run("""%s"" worker --config ""%s""", 0, True)
WScript.Quit rc
`, o.Interval, o.ExePath, o.ConfigPath)

	minutes := int(o.Interval.Minutes())
	if minutes < 1 {
		minutes = 1
	}
	xmlPath := filepath.Join(dir, "worker-task.xml")
	xmlBody := taskXML(minutes, vbs)

	if o.Print {
		fmt.Printf("Write %s:\n%s\n", vbs, content)
		fmt.Printf("Write %s:\n%s\n", xmlPath, xmlBody)
		fmt.Printf("Run: schtasks /create /tn %q /xml %q /f\n", o.Name, xmlPath)
		return nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(vbs, []byte(content), 0o644); err != nil {
		return err
	}
	if err := writeUTF16(xmlPath, xmlBody); err != nil {
		return err
	}

	cmd := exec.Command("schtasks", "/create", "/tn", o.Name, "/xml", xmlPath, "/f")
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		// Fall back to a direct /tr invocation. It fails on some Windows
		// builds when the command contains quotes, but it is worth trying.
		return fmt.Errorf("schtasks: %w", err)
	}
	fmt.Printf("installed scheduled task %q (every %d minute(s))\n", o.Name, minutes)
	return nil
}

func taskXML(minutes int, vbs string) string {
	start := time.Now().Add(time.Minute).Format("2006-01-02T15:04:05")
	return fmt.Sprintf(`<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>Git Airlock worker</Description>
  </RegistrationInfo>
  <Triggers>
    <TimeTrigger>
      <Repetition>
        <Interval>PT%dM</Interval>
        <StopAtDurationEnd>false</StopAtDurationEnd>
      </Repetition>
      <StartBoundary>%s</StartBoundary>
      <Enabled>true</Enabled>
    </TimeTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT10M</ExecutionTimeLimit>
    <Priority>7</Priority>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>wscript.exe</Command>
      <Arguments>%s</Arguments>
    </Exec>
  </Actions>
</Task>
`, minutes, start, html.EscapeString(`"`+vbs+`"`))
}

func writeUTF16(path, body string) error {
	units := utf16.Encode([]rune(body))
	buf := make([]byte, 2+len(units)*2)
	buf[0] = 0xFF
	buf[1] = 0xFE
	for i, u := range units {
		binary.LittleEndian.PutUint16(buf[2+i*2:], u)
	}
	return os.WriteFile(path, buf, 0o644)
}

func statusWindows(name string) (string, error) {
	out, err := exec.Command("schtasks", "/query", "/tn", name, "/fo", "list", "/v").Output()
	if err != nil {
		return "not installed", nil
	}
	for _, line := range strings.Split(string(out), "\n") {
		line = strings.TrimSpace(strings.TrimSuffix(line, "\r"))
		if strings.HasPrefix(line, "Status:") || strings.HasPrefix(line, "Stav:") {
			return strings.TrimSpace(line[strings.Index(line, ":")+1:]), nil
		}
	}
	return "unknown", nil
}
